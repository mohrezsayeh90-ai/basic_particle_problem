#!/usr/bin/env python3
"""Train one global parametric PINN; resumable chunks with periodic three-case exports."""
import argparse
from datetime import datetime,timezone
import json
import math
import os
from pathlib import Path
import random
import time
import traceback
os.environ.setdefault('MPLCONFIGDIR','/tmp/parametric-matplotlib')
import numpy as np
import torch
from particle_pinn.parametric import ParametricFlow,BASE,NAMES,anchors,sample_cases,map_points,coordinates,pde_residual
from particle_pinn.advanced_exports import PeriodicExporter,write_json


def batch(rng,size,step,curriculum_steps,device):
    span=min(1.,.15+.85*step/max(1,curriculum_steps))
    n=max(4,size//32)
    cases,_=sample_cases(rng,n,span)
    # Anchors augment the global sampled domain; they are not the only training cases.
    cases[:3]=np.array([c.array() for c in anchors().values()])
    values=np.repeat(cases[:,:3],math.ceil(size/n),axis=0)[:size]
    p=torch.as_tensor(values,dtype=torch.float32,device=device)
    q=torch.as_tensor(rng.uniform(.002,.998,size),dtype=torch.float32,device=device)
    eta=torch.as_tensor(rng.uniform(-.995,.995,size),dtype=torch.float32,device=device)
    xy=map_points(q,eta,p).detach().requires_grad_(True)
    return xy,p,cases


def objective(model,xy,p,cases):
    r=pde_residual(model,xy,p)
    physics=r.square().mean()
    # Cross-section integral uses independent quadrature points, including wall endpoints.
    c=torch.as_tensor(cases[:6,:3],dtype=torch.float32,device=p.device)
    pp=c.repeat_interleave(3*17,dim=0)
    q=torch.tensor([.2,.5,.8],device=p.device).repeat_interleave(17).repeat(len(c))
    eta=torch.linspace(-1,1,17,device=p.device).repeat(3*len(c))
    xx=map_points(q,eta,pp);_,_,t=coordinates(xx,pp)
    uv=model(xx,pp)[:,:2];ut=(uv*t).sum(1).reshape(len(c),3,17)
    flux=(torch.trapezoid(ut,torch.linspace(-1,1,17,device=p.device),dim=2)/(4/3)-1).square().mean()
    return physics+5*flux,physics,flux


def atomic_save(data,file):
    temp=file.with_suffix('.tmp');torch.save(data,temp);os.replace(temp,file)


def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--out',type=Path,required=True)
    parser.add_argument('--resume',type=Path)
    parser.add_argument('--total-steps',type=int,default=60000)
    parser.add_argument('--chunk-steps',type=int,default=1000)
    parser.add_argument('--snapshot-every',type=int,default=1000)
    parser.add_argument('--samples',type=int,default=1024)
    parser.add_argument('--width',type=int,default=128)
    parser.add_argument('--depth',type=int,default=6)
    parser.add_argument('--curriculum-steps',type=int,default=10000)
    parser.add_argument('--particles',type=int,default=5)
    parser.add_argument('--reference-ns',type=int,default=64)
    parser.add_argument('--reference-nn',type=int,default=14)
    parser.add_argument('--seed',type=int,default=42)
    parser.add_argument('--device',choices=['cpu','cuda','auto'],default='auto')
    parser.add_argument('--no-animation',action='store_true')
    args=parser.parse_args()
    for k in ['total_steps','chunk_steps','snapshot_every','samples','width','depth','particles']:
        if getattr(args,k)<1: parser.error(k+' must be positive')
    if args.samples<4: parser.error('samples must be >=4')
    if args.out.exists() and any(args.out.iterdir()): parser.error('Output folder is not empty')
    if args.device=='auto': args.device='cuda' if torch.cuda.is_available() else 'cpu'
    if args.device=='cuda' and not torch.cuda.is_available(): parser.error('CUDA is unavailable')
    torch.set_num_threads(2);torch.manual_seed(args.seed);random.seed(args.seed)
    rng=np.random.default_rng(args.seed);model=ParametricFlow(args.width,args.depth).to(args.device)
    opt=torch.optim.AdamW(model.parameters(),lr=8e-4,weight_decay=1e-6)
    scheduler=torch.optim.lr_scheduler.CosineAnnealingLR(opt,T_max=args.total_steps,eta_min=1e-5)
    start=0;history=[]
    if args.resume:
        # This checkpoint is generated by this workflow; never load unknown pickles.
        ck=torch.load(args.resume,map_location=args.device,weights_only=False)
        for k in ['total_steps','samples','width','depth','curriculum_steps','seed']:
            if ck['config'][k]!=getattr(args,k): parser.error('Resume configuration mismatch: '+k)
        if ck['scope']!='parametric-s-channel-v1': parser.error('Incompatible checkpoint')
        model.load_state_dict(ck['model']);opt.load_state_dict(ck['optimizer']);scheduler.load_state_dict(ck['scheduler'])
        rng.bit_generator.state=ck['numpy_rng'];torch.set_rng_state(ck['torch_rng'].cpu());random.setstate(ck['python_rng'])
        if args.device=='cuda' and ck.get('cuda_rng'): torch.cuda.set_rng_state_all([v.cpu() for v in ck['cuda_rng']])
        start=ck['step'];history=ck['history']
    if start>=args.total_steps: parser.error('Checkpoint already reached total steps')
    args.out.mkdir(parents=True);failures=[]
    config={k:str(v) if isinstance(v,Path) else v for k,v in vars(args).items()}
    config.update(parameters=dict(zip(NAMES,BASE.tolist())),parameter_factors=[.1,10],
        sampling='log-uniform conditional on rin<rout, h/R<=0.85, diameter<width',
        architecture='5 inputs; 6x128 tanh default; outputs u,v,p; exact wall/cap velocity',
        particle_model='One-way isolated-sphere Schiller-Naumann drag, sticking walls; no lift, gravity or particle interactions',
        time_independent_flow=True)
    write_json(args.out/'config.json',config)
    started=time.time();exporter=PeriodicExporter(args.out,args.seed,args.particles,args.reference_ns,args.reference_nn,not args.no_animation)
    end=min(args.total_steps,start+args.chunk_steps);last=start
    def save(step):
        atomic_save(dict(scope='parametric-s-channel-v1',step=step,model=model.state_dict(),optimizer=opt.state_dict(),
            scheduler=scheduler.state_dict(),numpy_rng=rng.bit_generator.state,torch_rng=torch.get_rng_state(),
            cuda_rng=torch.cuda.get_rng_state_all() if args.device=='cuda' else None,python_rng=random.getstate(),
            config=config,history=history),args.out/'checkpoint.pt')
    try:
        for step in range(start+1,end+1):
            model.train();xy,p,cases=batch(rng,args.samples,step,args.curriculum_steps,args.device)
            opt.zero_grad(set_to_none=True);loss,physics,flux=objective(model,xy,p,cases)
            if not torch.isfinite(loss): raise FloatingPointError('Non-finite training loss')
            loss.backward();norm=torch.nn.utils.clip_grad_norm_(model.parameters(),10.)
            if not torch.isfinite(norm): raise FloatingPointError('Non-finite gradients')
            opt.step();scheduler.step();last=step
            if step%25==0 or step%args.snapshot_every==0 or step==end:
                record=dict(step=step,total=float(loss.detach()),physics=float(physics.detach()),flux=float(flux.detach()),lr=scheduler.get_last_lr()[0])
                history.append(record);print(json.dumps(record),flush=True)
            if step%args.snapshot_every==0 or step==end:
                save(step);model.eval()
                try: exporter.export(model,step,history)
                except Exception as e: failures.append(dict(stage='export',step=step,error=str(e),traceback=traceback.format_exc()))
    except Exception as error:
        failures.append(dict(stage='training',step=last,error=str(error),traceback=traceback.format_exc()))
        save(last)
        try:
            folder=args.out/'snapshots'/f'step_{last:06d}'
            if not folder.exists(): model.eval();exporter.export(model,last,history)
        except Exception as e: failures.append(dict(stage='final_export',error=str(e)))
    write_json(args.out/'failures.json',failures)
    write_json(args.out/'chunk_complete.json',dict(start_step=start,step=last,target_steps=args.total_steps,
        reached_chunk_target=last==end,training_complete=last==args.total_steps,execution_failures=len(failures),
        elapsed_seconds=time.time()-started,device=args.device,
        gpu=torch.cuda.get_device_name(0) if args.device=='cuda' else None,
        timestamp_utc=datetime.now(timezone.utc).isoformat()))
    print('Chunk saved:',str(args.out.resolve()),flush=True)
    return 2 if failures else 0


if __name__=='__main__': raise SystemExit(main())
